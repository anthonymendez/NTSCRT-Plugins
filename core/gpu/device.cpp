// device.cpp — backend selection and the embedded-shader registry.
#include <cstdio>
#include <cstdlib>
#include <mutex>
#include <vector>

#include "backend.h"

extern "C" void ntscrt_shaders_anchor_ntscrt_core(void);  // generated by ntscrt_add_shaders

namespace ntscrt::gpu {

namespace {
std::vector<const ShaderFile *> &files() {
    static std::vector<const ShaderFile *> f;
    return f;
}
std::mutex &files_mutex() {
    static std::mutex m;
    return m;
}
// Per thread: create() may run on several threads at once (one per host
// instance), and each caller reads the reason right after its own call.
std::string &create_error() {
    thread_local std::string e;
    return e;
}

bool sharing_enabled() {
    const char *e = std::getenv("NTSCRT_SHARED_DEVICE");
    return !(e && *e == '0');
}
}  // namespace

void register_shader_files(const ShaderFile *const *f, size_t n) {
    std::lock_guard<std::mutex> lock(files_mutex());
    files().insert(files().end(), f, f + n);
}

const ShaderEntry *find_shader(std::string_view name, const ShaderFile **file_out) {
    auto slash = name.find('/');
    if (slash == std::string_view::npos) return nullptr;
    std::string_view stem = name.substr(0, slash), entry = name.substr(slash + 1);
    std::lock_guard<std::mutex> lock(files_mutex());
    for (const ShaderFile *f : files()) {
        if (stem != f->stem) continue;
        for (size_t i = 0; i < f->count; ++i)
            if (entry == f->entries[i].name) {
                if (file_out) *file_out = f;
                return &f->entries[i];
            }
    }
    return nullptr;
}

const char *Device::last_create_error() { return create_error().c_str(); }

std::unique_ptr<Device> Device::create(Backend backend, void *native_device, void *native_queue) {
    ntscrt_shaders_anchor_ntscrt_core();
    std::string err;
    std::unique_ptr<Device> d;
    try {
        if (backend == Backend::D3D11) d = create_d3d11_device(native_device, err);
        else d = create_metal_device(native_device, native_queue, err);
    } catch (const std::exception &e) {
        err = e.what();
        d.reset();
    } catch (...) {
        err = "unknown exception while creating the GPU device";
        d.reset();
    }
    create_error() = d ? std::string() : err;
    if (!d) std::fprintf(stderr, "ntscrt: no GPU device: %s\n", err.c_str());
    return d;
}

std::shared_ptr<Device> Device::shared(Backend backend) {
    if (!sharing_enabled()) return create(backend, nullptr, nullptr);
    // Weak references: the device dies with its last user (ntscrt_destroy),
    // never in a static destructor (under the loader lock on DLL unload).
    static std::mutex m;
    static std::weak_ptr<Device> devices[2];
    std::lock_guard<std::mutex> lock(m);
    std::weak_ptr<Device> &slot = devices[backend == Backend::D3D11 ? 0 : 1];
    if (auto d = slot.lock(); d && !d->lost()) {
        create_error().clear();
        return d;
    }
    std::shared_ptr<Device> d = create(backend, nullptr, nullptr);
    if (d) slot = d;
    return d;
}

#if !defined(_WIN32)
std::unique_ptr<Device> create_d3d11_device(void *, std::string &err) {
    err = "Direct3D 11 is only available on Windows";
    return nullptr;
}
#endif
#if !defined(__APPLE__)
std::unique_ptr<Device> create_metal_device(void *, void *, std::string &err) {
    err = "Metal is only available on macOS";
    return nullptr;
}
#endif

}  // namespace ntscrt::gpu
