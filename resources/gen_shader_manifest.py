#!/usr/bin/env python3
"""Regenerate resources/shader-manifest.txt: every file under vendor/slang-shaders
that the bundled CRT presets need (preset files, #reference'd presets, pass
.slang files, their #include closure, LUT textures). The build copies exactly
these files into <resources>/shaders/, preserving relative paths.

Also prints which presets use temporal inputs (OriginalHistory, PassFeedback,
alias feedback, FrameCount) so hosts know what needs sequential state.

usage: python3 resources/gen_shader_manifest.py [slang-shaders-root]
"""
import os
import re
import sys

PRESETS = [  # upstream Sources/CrtCore/Presets.swift
    "crt/crt-aperture.slangp",
    "crt/crt-easymode.slangp",
    "crt/crtglow_gauss.slangp",
    "crt/crtglow_lanczos.slangp",
    "crt/crt-hyllian.slangp",
    "crt/crt-royale.slangp",
    "crt/crtsim.slangp",
]

# Licence files shipped beside the shaders that need them (GPL: the licence text
# travels with the files; THIRD_PARTY_NOTICES.md lists the rest).
EXTRA = [
    "crt/shaders/crt-royale/LICENSE.TXT",
]

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "vendor", "slang-shaders")
ROOT = os.path.abspath(ROOT)


def rel(p):
    return os.path.relpath(p, ROOT).replace("\\", "/")


def norm(base_dir, value):
    return os.path.normpath(os.path.join(base_dir, value.strip().strip('"')))


def parse_preset(path, files, slangs):
    files.add(rel(path))
    d = os.path.dirname(path)
    kv = {}
    for line in open(path, encoding="utf-8", errors="replace"):
        line = line.split("#", 1)[0] if not line.lstrip().startswith("#reference") else line
        s = line.strip()
        if s.startswith("#reference"):
            ref = norm(d, s[len("#reference"):])
            parse_preset(ref, files, slangs)
            continue
        if "=" not in s:
            continue
        k, v = s.split("=", 1)
        kv[k.strip()] = v.strip().strip('"')
    for k, v in kv.items():
        if re.fullmatch(r"shader\d+", k):
            p = norm(d, v)
            slangs.add(p)
    for name in [t for t in kv.get("textures", "").split(";") if t]:
        if name in kv:
            files.add(rel(norm(d, kv[name])))


def include_closure(p, files, seen):
    if p in seen:
        return
    seen.add(p)
    files.add(rel(p))
    d = os.path.dirname(p)
    for line in open(p, encoding="utf-8", errors="replace"):
        m = re.match(r'\s*#\s*include\s+"([^"]+)"', line)
        if m:
            include_closure(norm(d, m.group(1)), files, seen)


TEMPORAL = re.compile(r"\b(OriginalHistory\d*|PassFeedback\d+|\w+Feedback|PassOutput\d+|FrameCount|FrameDirection)\b")


def main():
    allfiles = set()
    for preset in PRESETS:
        files, slangs, seen = set(), set(), set()
        parse_preset(os.path.join(ROOT, preset), files, slangs)
        for s in slangs:
            include_closure(s, files, seen)
        hits = set()
        for f in files:
            if f.endswith((".slang", ".h", ".inc")):
                for line in open(os.path.join(ROOT, f), encoding="utf-8", errors="replace"):
                    code = line.split("//", 1)[0]
                    for m in TEMPORAL.finditer(code):
                        hits.add(m.group(1))
        print(f"{preset}: {len(files)} files; temporal refs: {sorted(hits) or 'none'}", file=sys.stderr)
        allfiles |= files
    allfiles |= set(EXTRA)
    missing = [f for f in allfiles if not os.path.exists(os.path.join(ROOT, f))]
    if missing:
        sys.exit("missing: " + ", ".join(sorted(missing)))
    with open(os.path.join(HERE, "shader-manifest.txt"), "w", newline="\n") as out:
        out.write("# Generated by resources/gen_shader_manifest.py -- files copied from\n")
        out.write("# vendor/slang-shaders into <resources>/shaders/ (relative paths kept).\n")
        for f in sorted(allfiles):
            out.write(f + "\n")
    print(f"{len(allfiles)} files", file=sys.stderr)


main()
